test('专属 MCP 凭据与原项目分离；拒绝无凭据、错误来源，端口变化后配置仍使用同一凭据', async t => {
  const root = await fs.mkdtemp(path.resolve(__dirname, '../../work/tmp/mcp-test-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const store = await new ConfigStore(root, async s => Buffer.from(s), async b => b.toString()).initialize();
  const gateway = new Gateway({ store, root, log() {} }); const url = await gateway.listen(0);
  assert.equal((await fetch(url + '/mcp/canvas', { method: 'POST', body: '{}' })).status, 401);
  assert.equal((await fetch(url + '/mcp/director', { method: 'POST', headers: { authorization: 'Bearer ' + gateway.mcpToken, origin: 'https://other.example' }, body: '{}' })).status, 403);
  assert.equal((await fetch(url + '/local/mcp/config')).status, 401);
  const headers = { cookie: `canvas_session=${gateway.cookie}` };
  const config = await (await fetch(url + '/local/mcp/config', { headers })).json();
  assert.deepEqual(Object.keys(config.mcpServers), ['canvas-studio-canvas','canvas-studio-director']);
  assert.ok(config.mcpServers['canvas-studio-canvas'].args.includes(path.join(store.dataDir, 'config/mcp-connection.json')));
  assert.ok(!JSON.stringify(config).includes('@tigerowo'));
  assert.match(config.instructions['canvas-studio-canvas'], /canvas_studio_list_canvases/);
  assert.match(config.instructions['canvas-studio-director'], /canvas_studio_director_list_workspaces/);
  assert.ok(!JSON.stringify(config.instructions).includes(gateway.mcpToken));
  const saved = JSON.parse(await fs.readFile(gateway.mcpConfigFile, 'utf8'));
  assert.equal(saved.token.length, 64);
  await gateway.close();
  const reopened = new Gateway({ store, root, log() {} }); await reopened.listen(0); t.after(() => reopened.close());
  assert.equal(reopened.mcpToken, saved.token);
});

test('本机文件选择可取消并使用单次凭据读取，FOR 仅预览快照中的图片', async t => {
  const root = await fs.mkdtemp(path.resolve(__dirname, '../../work/tmp/picker-test-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const folder = path.join(root, '输入图');
  await fs.mkdir(folder);
  const first = path.join(folder, '图1.png');
  const second = path.join(folder, '图2.jpg');
  await fs.writeFile(first, 'first image');
  await fs.writeFile(second, 'second image');
  const store = await new ConfigStore(root).initialize();
  let picks = [];
  const gateway = new Gateway({ store, root, log() {}, chooseFolder: async () => folder, chooseMedia: async () => picks });
  const origin = await gateway.listen(0); t.after(() => gateway.close());
  const headers = { cookie: `canvas_session=${gateway.cookie}`, 'content-type': 'application/json' };
  const post = (route, value) => fetch(origin + route, { method: 'POST', headers, body: JSON.stringify(value) });
  assert.deepEqual(await (await post('/local/media/select', { kind: 'image' })).json(), []);
  picks = [first];
  const [picked] = await (await post('/local/media/select', { kind: 'image' })).json();
  assert.equal(picked.name, '图1.png');
  assert.equal(picked.real, undefined);
  assert.equal((await fetch(origin + '/local/media/picked/' + picked.id)).status, 401);
  assert.equal(await (await fetch(origin + '/local/media/picked/' + picked.id, { headers })).text(), 'first image');
  assert.equal((await fetch(origin + '/local/media/picked/' + picked.id, { headers })).status, 500);
  const selection = await (await post('/local/folders/select', {})).json();
  const { files } = await (await fetch(origin + '/local/folders/' + selection.id, { headers })).json();
  const preview = item => fetch(origin + '/local/folders/' + selection.id + '/preview?' + new URLSearchParams({ file: item.id, size: item.size, mtime: item.mtime }), { headers });
  assert.equal(await (await preview(files[0])).text(), 'first image');
  assert.equal(await (await preview(files[1])).text(), 'second image');
  assert.equal((await preview({ ...files[0], id: Buffer.from('../outside.png').toString('base64url') })).status, 500);
  await fs.writeFile(first, 'modified');
  assert.equal((await preview(files[0])).status, 500);
});

test('素材另存保留扩展名、处理重名和取消，自动保存跨重启去重并报告目录不可用', async t => {
  const root = await fs.mkdtemp(path.resolve(__dirname, '../../work/tmp/exports-test-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const destination = path.join(root, '生成 文件');
  const assets = path.join(root, 'assets');
  await fs.mkdir(assets);
  await fs.mkdir(destination);
  const id = '12345678-1234-1234-1234-123456789abc';
  const nextId = '12345678-1234-1234-1234-123456789abd';
  const thirdId = '12345678-1234-1234-1234-123456789abe';
  for (const asset of [id, nextId, thirdId]) await fs.writeFile(path.join(assets, asset + '.webp'), 'test image');
  const sha256 = createHash('sha256').update('test image').digest('hex');
  const api = http.createServer((req, res) => {
    const id = req.url.split('/').at(-1);
    res.writeHead(200, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ code: 0, data: { id, objectKey: id + '.webp', providerId: 'local-disk', mimeType: 'image/webp', bytes: 10, sha256 } }));
  });
  await new Promise(resolve => api.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => api.close(resolve)));
  let chosen;
  const options = { apiPort: api.address().port, token: 'fixture', choose: async () => chosen };
  const exporter = new MediaExports(root, options);
  assert.equal(await exporter.manual(id, '图片'), null);
  assert.equal(await exporter.automatic(id, Date.now()), null);
  chosen = destination;
  assert.deepEqual(await exporter.manual(id, '图片.webp'), { name: '图片.webp' });
  assert.deepEqual(await exporter.manual(id, '图片.webp'), { name: '图片 (2).webp' });
  const settings = await exporter.configure({ directory: destination, enabled: true });
  assert.equal(await exporter.automatic(id, settings.enabledAt - 1), null);
  const simultaneous = await Promise.all([exporter.automatic(id, Date.now()), exporter.automatic(id, Date.now())]);
  assert.deepEqual(simultaneous[0], simultaneous[1]);
  const reopened = new MediaExports(root, options);
  assert.equal(await reopened.automatic(id, Date.now()), null);
  assert.equal((await fs.readdir(destination)).length, 3);
  assert.equal(await fs.readFile(path.join(destination, simultaneous[0].name), 'utf8'), 'test image');
  await fs.unlink(path.join(root, 'config', 'exported-media', id + '.json'));
  assert.deepEqual(await reopened.automatic(id, Date.now()), simultaneous[0]);
  assert.equal((await fs.readdir(destination)).length, 3);
  await fs.writeFile(path.join(destination, `生成-${nextId}.webp`), 'wrong file');
  const second = await reopened.automatic(nextId, Date.now());
  assert.equal(second.name, `生成-${nextId} (2).webp`);
  assert.equal(await fs.readFile(path.join(destination, second.name), 'utf8'), 'test image');
  const generated = await reopened.automatic(id, Date.now(), 'image:task-1:0');
  assert.ok(generated.name.endsWith('.webp'));
  assert.equal(await reopened.automatic(nextId, Date.now(), 'image:task-1:0'), null);
  await fs.rename(destination, destination + '-离线');
  await assert.rejects(() => reopened.automatic(thirdId, Date.now()), /输出目录不可用/);
  assert.equal(await fs.readFile(path.join(assets, thirdId + '.webp'), 'utf8'), 'test image');
});

test('画布 MCP 独立工具命名，多画布必须指定目标，取消请求会通知页面', async () => {
  const bridge = new CanvasBridge(), events = [];
  const session = id => ({ id, canvasId: 'canvas-' + id, events: { write: text => events.push(text), end() {} }, tools: [{ name: 'get_canvas_summary', inputSchema: { type: 'object', properties: {} } }], pending: new Map() });
  bridge.sessions.set('one', session('one')); bridge.sessions.set('two', session('two'));
  assert.equal(bridge.tools()[1].name, 'canvas_studio_get_canvas_summary');
  await assert.rejects(() => bridge.call('canvas_studio_get_canvas_summary', {}), /workspace_id/);
  const abort = new AbortController();
  const result = bridge.call('canvas_studio_get_canvas_summary', { workspace_id: 'two' }, abort.signal);
  assert.equal(bridge.sessions.get('one').pending.size, 0);
  const pending = [...bridge.sessions.get('two').pending.values()][0]; pending.resolve({ ok: true, id: 'two' });
  assert.deepEqual(await result, { ok: true, id: 'two' });
  const canceled = bridge.call('canvas_studio_get_canvas_summary', { workspace_id: 'one' }, abort.signal); abort.abort();
  await assert.rejects(() => canceled, /取消/); assert.ok(events.some(e => e.includes('tool-cancel')));
  assert.equal(bridge.sessions.get('one').pending.size, 0); bridge.close();
});

test('文件夹循环只读取用户选择的文件夹，中文路径、自然排序、子目录、文件变更和越界保护', async t => {
  const root = await fs.mkdtemp(path.resolve(__dirname, '../../work/tmp/folder-test-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const input = path.join(root, '输入素材'); await fs.mkdir(path.join(input, '子目录'), { recursive: true });
  await fs.writeFile(path.join(input, '第10份.txt'), '十'); await fs.writeFile(path.join(input, '第2份.txt'), '二'); await fs.writeFile(path.join(input, '子目录', '文本.md'), '子文件');
  await fs.symlink(path.join(root, 'outside.txt'), path.join(input, '跳过.txt')); await fs.writeFile(path.join(root, 'outside.txt'), '不应读取');
  const store = new FolderStore(root, async () => input); const selected = await store.select();
  const scan = await store.scan(selected.id); assert.deepEqual(scan.files.map(f => f.relativePath), ['第2份.txt', '第10份.txt']);
  assert.equal((await store.scan(selected.id, true)).files.length, 3);
  assert.equal((await store.import(selected.id, scan.files[0])).content, '二');
  const reopened = new FolderStore(root); assert.equal((await reopened.scan(selected.id)).files.length, 2);
  await assert.rejects(() => store.import(selected.id, { ...scan.files[0], id: Buffer.from('../outside.txt').toString('base64url') }), /超出/);
  await fs.writeFile(path.join(input, '第2份.txt'), '已改变'); await assert.rejects(() => store.import(selected.id, scan.files[0]), /修改/);
  await fs.rename(input, input + '-removed'); await assert.rejects(() => store.scan(selected.id)); await assert.rejects(() => fs.stat(input));
});
